/** "1.84.1" before "1.85.0": versions compared number by number. */
export function isNewerVersion(a: string, b: string): boolean {
  const [x, y] = [a, b].map((v) => v.split('.').map(Number))
  for (let i = 0; i < 3; i++) if (x![i] !== y![i]) return (x![i] ?? 0) > (y![i] ?? 0)
  return false
}

