export function releasesSince(from: string, to: string = APP_VERSION): Release[] {
  if (!CHANGELOG.some((r) => r.version === from)) return []
  return CHANGELOG.filter((r) => isNewerVersion(r.version, from) && !isNewerVersion(r.version, to))
}
